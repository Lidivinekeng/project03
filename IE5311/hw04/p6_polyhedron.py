from fractions import Fraction

from ppl import Variable, C_Polyhedron, Constraint_System

x, y, u, v = Variable(0), Variable(1), Variable(2), Variable(3)
NAMES = ("x", "y", "u", "v")
LABEL = ("x >= 0", "x <= 1", "y >= 0", "y <= 1",
         "u >= 0", "v >= 0", "u - v <= 0", "x + y <= 2")
ROWS = (x >= 0, x <= 1, y >= 0, y <= 1,
        u >= 0, v >= 0, u - v <= 0, x + y <= 2)
HOMOGENEOUS = (x >= 0, x <= 0, y >= 0, y <= 0,
               u >= 0, v >= 0, u - v <= 0, x + y <= 0)


def build(rows):
    cs = Constraint_System()
    for r in rows:
        cs.insert(r)
    return C_Polyhedron(cs)


def split(poly):
    pts, rays, lines = [], [], []
    for g in poly.minimized_generators():
        c = [int(k) for k in g.coefficients()]
        if g.is_point():
            d = int(g.divisor())
            pts.append(tuple(Fraction(k, d) for k in c))
        elif g.is_ray():
            rays.append(tuple(c))
        else:
            lines.append(tuple(c))
    return sorted(pts), sorted(rays), sorted(lines)


def fmt(t):
    return "(" + ", ".join(str(k) for k in t) + ")"


P = build(ROWS)

print("=" * 64)
print("PROBLEM 6:  P subset of R^4 with coordinates (x, y, u, v)")
print("=" * 64)
for lab in LABEL:
    print("   ", lab)

print("\nPART 1: full-dimensional?")
print("    affine dimension:", P.affine_dimension(), "and the space is R^4")
print("    full-dimensional:", P.affine_dimension() == 4)
interior = (Fraction(1, 2), Fraction(1, 2), 1, 2)
print("    witness, every row strict at (x,y,u,v) =", fmt(interior))

print("\nPART 2: recession cone")
R = build(HOMOGENEOUS)
rpts, rrays, rlines = split(R)
print("    description: {(0, 0, du, dv) : 0 <= du <= dv}")
print("    minimized constraints:")
for c in R.minimized_constraints():
    print("       ", c)
print("    generated by:", ", ".join(fmt(r) for r in rrays))
print("    lines:", rlines, "so the cone is pointed")

pts, rays, lines = split(P)
print("\nPART 3(a): extreme points —", len(pts))
for p in pts:
    print("   ", fmt(p))

print("\nPART 3(b): extreme rays —", len(rays))
for r in rays:
    print("   ", fmt(r))
print("    these match the generators of the recession cone:",
      rays == rrays)

print("\nPART 3(c): facets — the irredundant inequalities")
mc = list(P.minimized_constraints())
print("    count:", len(mc))
for c in mc:
    print("       ", c)

print("\nPART 3(d): redundant rows of the given description")
for i, lab in enumerate(LABEL):
    kept = [r for j, r in enumerate(ROWS) if j != i]
    same = build(kept) == P
    print(f"    drop [{lab:<12}] -> P unchanged: {str(same):<5} "
          f"{'REDUNDANT' if same else 'facet-defining'}")

print("\nPART 4: cross-check against the hand-derived answers")
want_pts = sorted([(Fraction(a), Fraction(b), Fraction(0), Fraction(0))
                   for a in (0, 1) for b in (0, 1)])
want_rays = sorted([(0, 0, 0, 1), (0, 0, 1, 1)])
print("    extreme points match:", pts == want_pts)
print("    extreme rays match  :", rays == want_rays)
print("    facet count is 6    :", len(mc) == 6)
print("    exactly v >= 0 and x + y <= 2 are redundant:",
      [LABEL[i] for i in range(len(ROWS))
       if build([r for j, r in enumerate(ROWS) if j != i]) == P]
      == ["v >= 0", "x + y <= 2"])
