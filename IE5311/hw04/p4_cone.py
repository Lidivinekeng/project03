import io
import math
import re

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Polygon
from ppl import Variable, C_Polyhedron, Constraint_System

TEX = "hw04_solutions.tex"
BEGIN = "% BEGIN p4 figure (generated by p4_cone.py)"
END = "% END p4 figure"

SA = 2.0
SB = 0.95
COS30 = math.cos(math.radians(30.0))
OFF_A, OFF_B, OFF_C = 0.0, 7.0, 11.6
LIM = 1.6
TMAX = 2.0


def iso(p):
    a, b, c = p
    return ((a - b) * COS30 * SB, ((a + b) * 0.5 + c) * SB)


def flat(p, off):
    return (off + p[0] * SA, p[1] * SA)


def shift(pt, off):
    return (off + pt[0], pt[1])


def primitives():
    out = []

    for off in (OFF_A, OFF_C):
        out.append(("axis", [(off - 0.35, 0.0), (off + LIM * SA + 0.3, 0.0)]))
        out.append(("axis", [(off, -0.35), (off, LIM * SA + 0.3)]))

    out.append(("fill", [flat((0, 0), OFF_C), flat((LIM, 0), OFF_C),
                         flat((LIM, LIM), OFF_C), flat((0, LIM), OFF_C)]))

    for off in (OFF_A, OFF_C):
        out.append(("heavy", [flat((1, 0), off), flat((0, 1), off)]))
    for off in (OFF_A,):
        out.append(("dot", [flat((1, 0), off)]))
        out.append(("dot", [flat((0, 1), off)]))

    tri = [shift(iso(p), OFF_B)
           for p in ((0, 0, 0), (TMAX, 0, TMAX), (0, TMAX, TMAX))]
    out.append(("fill", tri))
    for end in ((TMAX, 0, TMAX), (0, TMAX, TMAX)):
        out.append(("heavy", [shift(iso((0, 0, 0)), OFF_B),
                              shift(iso(end), OFF_B)]))
    out.append(("heavy", [shift(iso((1, 0, 1)), OFF_B),
                          shift(iso((0, 1, 1)), OFF_B)]))
    out.append(("dot", [shift(iso((1, 0, 1)), OFF_B)]))
    out.append(("dot", [shift(iso((0, 1, 1)), OFF_B)]))
    for end in ((2.45, 0, 0), (0, 2.45, 0), (0, 0, 3.35)):
        out.append(("axis", [shift(iso((0, 0, 0)), OFF_B),
                             shift(iso(end), OFF_B)]))

    labels = [
        (shift((LIM * SA + 0.45, -0.05), OFF_A), "$x_1$"),
        (shift((-0.3, LIM * SA + 0.35), OFF_A), "$x_2$"),
        (shift(iso((2.75, 0, 0)), OFF_B), "$y_1$"),
        (shift(iso((0, 2.75, 0)), OFF_B), "$y_2$"),
        (shift(iso((0, 0, 3.6)), OFF_B), "$t$"),
        (shift((LIM * SA + 0.45, -0.05), OFF_C), "$y_1$"),
        (shift((-0.3, LIM * SA + 0.35), OFF_C), "$y_2$"),
    ]
    titles = [
        (OFF_A + LIM * SA / 2, -0.95, "$U$"),
        (OFF_B, -0.95, "$\\mathcal{C}_U$"),
        (OFF_C + LIM * SA / 2, -0.95,
         "$\\mathrm{Proj}_{\\mathbb{R}^2}(\\mathcal{C}_U)=\\mathbb{R}^2_+$"),
    ]
    return out, labels, titles


def preview():
    out, labels, titles = primitives()
    fig, ax = plt.subplots(figsize=(9.2, 3.2))
    for kind, pts in out:
        if kind == "fill":
            ax.add_patch(Polygon(pts, facecolor="0.80", edgecolor="none",
                                 alpha=0.6))
        elif kind == "axis":
            ax.plot(*zip(*pts), color="0.45", linewidth=0.7)
        elif kind == "heavy":
            ax.plot(*zip(*pts), color="black", linewidth=1.8)
        elif kind == "dot":
            ax.plot(*zip(*pts), "o", color="black", markersize=4)
    for (x, y), t in labels:
        ax.text(x, y, t, fontsize=9, ha="center", va="center")
    for x, y, t in titles:
        ax.text(x, y, t, fontsize=10, ha="center", va="center")
    ax.set_xlim(-0.9, 16.0)
    ax.set_ylim(-1.5, 4.0)
    ax.set_aspect("equal")
    ax.axis("off")
    fig.tight_layout()
    fig.savefig("p4_cone.pdf")
    fig.savefig("p4_cone.png", dpi=170)
    print("wrote p4_cone.pdf and p4_cone.png")


def tikz():
    out, labels, titles = primitives()
    L = [BEGIN, r"\begin{figure}[htbp]", r"\centering",
         r"\begin{tikzpicture}[x=1cm,y=1cm]"]
    for kind, pts in out:
        c = " -- ".join(f"({x:.4f},{y:.4f})" for x, y in pts)
        if kind == "fill":
            L.append(f"\\fill[black!20] {c} -- cycle;")
        elif kind == "axis":
            L.append(f"\\draw[black!55,line width=0.35pt] {c};")
        elif kind == "heavy":
            L.append(f"\\draw[black,line width=0.9pt] {c};")
        elif kind == "dot":
            L.append(f"\\fill[black] {c} circle (1.5pt);")
    for (x, y), t in labels:
        L.append(f"\\node[font=\\small] at ({x:.4f},{y:.4f}) {{{t}}};")
    for x, y, t in titles:
        L.append(f"\\node at ({x:.4f},{y:.4f}) {{{t}}};")
    L += [r"\end{tikzpicture}",
          r"\caption{Left: $U$, the segment from $(1,0)$ to $(0,1)$.",
          r"Centre: $\mathcal{C}_U$ truncated at $t \le 2$. The cone lies",
          r"in the plane $y_1+y_2=t$, so it is flat and the truncation is",
          r"a triangle with apex at the origin; the heavy segment across",
          r"it is the slice $t=1$, a copy of $U$. Right: the projection",
          r"onto $(y_1,y_2)$, the whole nonnegative orthant, with $U$ drawn",
          r"in. Geometry and coordinates computed by \texttt{p4\_cone.py},",
          r"which renders the same figure with matplotlib and emits this",
          r"block.}",
          r"\end{figure}", END]
    block = "\n".join(L)

    src = io.open(TEX, encoding="utf-8").read()
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if pat.search(src):
        src = pat.sub(lambda _: block, src)
        print("replaced the generated figure block")
    else:
        fig = re.compile(r"\\begin\{figure\}\[htbp\].*?\\end\{figure\}", re.S)
        src, n = fig.subn(lambda _: block, src, count=1)
        if n != 1:
            raise SystemExit("could not find the figure environment")
        print("inserted the figure block in place of the graphics include")
    io.open(TEX, "w", encoding="utf-8").write(src)
    print(f"{len(out)} drawing primitives written into {TEX}")


def report():
    y1, y2, t = Variable(0), Variable(1), Variable(2)
    cs = Constraint_System()
    cs.insert(y1 >= 0)
    cs.insert(y2 >= 0)
    cs.insert(y1 + y2 - t == 0)
    cu = C_Polyhedron(cs)
    print("C_U = {(y1,y2,t) : y1 >= 0, y2 >= 0, y1 + y2 - t = 0}")
    print("affine dimension:", cu.affine_dimension())
    for g in cu.minimized_generators():
        print("   ", g)
    cs.insert(t <= -1)
    print("t >= 0 is implied:", C_Polyhedron(cs).is_empty())

    pr = C_Polyhedron(cu)
    pr.remove_higher_space_dimensions(2)
    print("projection onto (y1,y2):")
    for c in pr.minimized_constraints():
        print("   ", c)
    for g in pr.minimized_generators():
        print("   ", g)
    print("projection equals the nonnegative orthant = cone(U)")


if __name__ == "__main__":
    report()
    preview()
    tikz()
