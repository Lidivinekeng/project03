import itertools

import numpy as np

ELEMS = ["a", "b", "c", "d"]
TURN = {"a": 0, "b": 1, "c": 2, "d": 3}
BACK = {v: k for k, v in TURN.items()}


def mul(x, y):
    return BACK[(TURN[x] + TURN[y]) % 4]


def cayley():
    return {(x, y): mul(x, y) for x in ELEMS for y in ELEMS}


def identity_of(tab, elems):
    for e in elems:
        if all(tab[(e, x)] == x and tab[(x, e)] == x for x in elems):
            return e
    return None


def inverses(tab, elems, e):
    return {x: [y for y in elems if tab[(x, y)] == e and tab[(y, x)] == e]
            for x in elems}


